from typing import Any, List, Optional
from pydantic import BaseModel, Field


class AnalyzeRequest(BaseModel):
    """
    Inbound payload generated by the mobile client's Edge OCR pipeline.
    """
    ocr_text: str = Field(..., description="Cleaned OCR text from edge recognition")
    raw_text: Optional[str] = Field(None, description="Raw unnormalized OCR text")
    isolated_ingredients: Optional[str] = Field(None, description="Isolate ingredient listing text")
    profile_id: Optional[str] = Field(None, description="UUID of active dietary profile")
    raw_lines: Optional[List[str]] = Field(default_factory=list, description="Raw line-by-line OCR segments")
    has_ingredient_keywords: Optional[bool] = Field(False, description="Whether ingredient headers were detected")
    client_metadata: Optional[dict[str, Any]] = Field(default_factory=dict, description="Device & preprocessing telemetry")


class DetectedIngredient(BaseModel):
    name: str = Field(..., description="Detected ingredient segment")
    matched_standard: Optional[str] = Field(None, description="Canonical standardized ingredient name")
    category: Optional[str] = Field(None, description="Food category taxonomy")
    confidence: float = Field(..., description="Confidence score of entity extraction (0.0 to 1.0)")
    is_additive: bool = Field(False, description="Whether entity is an E-number or chemical additive")


class MatchedAllergen(BaseModel):
    allergen_code: str = Field(..., description="Canonical allergen code (e.g. peanut, milk, gluten)")
    allergen_name: str = Field(..., description="Human-readable allergen name")
    severity_level: str = Field("severe", description="Severity associated with active profile or default")
    cross_reactivity: str = Field("direct", description="Risk type: direct, cross_reactive, trace")
    matched_ingredient: str = Field(..., description="Ingredient that triggered this allergen")
    is_profile_conflict: bool = Field(..., description="True if actively flagged in user's dietary profile")
    notes: Optional[str] = Field(None, description="Clinical or culinary notes")


class DetectedAdditive(BaseModel):
    e_number: str = Field(..., description="Standardized E-number or INS code (e.g. E102, E621)")
    name: str = Field(..., description="Common additive chemical name")
    category: str = Field(..., description="Functional group (e.g. Color, Preservative, Sweetener)")
    risk_level: str = Field("caution", description="Regulatory safety tier: safe, caution, danger")
    explanation: Optional[str] = Field(None, description="Additive explanation")
    health_concerns: Optional[str] = Field(None, description="Known sensitivities or medical concerns")


class ProfileEvaluationSummary(BaseModel):
    profile_id: Optional[str] = None
    profile_name: Optional[str] = "Default / Guest"
    active_allergens_count: int = 0
    matched_conflicts_count: int = 0


class AnalyzeResponse(BaseModel):
    """
    Standardized inference verdict returned to the FoodLence mobile application.
    """
    status: str = Field("success", description="API response status")
    safety_verdict: str = Field(..., description="Deterministic verdict: SAFE, CAUTION, UNSAFE")
    verdict_color: str = Field(..., description="UI indicator color: green, yellow, red")
    summary: str = Field(..., description="Concise human-readable explanation of safety verdict")
    confidence_score: float = Field(..., description="Aggregated confidence percentage (0.0 to 1.0)")
    requires_manual_check: bool = Field(False, description="Flagged true if confidence falls below threshold")
    detected_ingredients: List[DetectedIngredient] = Field(default_factory=list)
    matched_allergens: List[MatchedAllergen] = Field(default_factory=list)
    detected_additives: List[DetectedAdditive] = Field(default_factory=list)
    profile_evaluated: Optional[ProfileEvaluationSummary] = None
    processing_time_ms: float = Field(..., description="Total backend inference latency in milliseconds")
